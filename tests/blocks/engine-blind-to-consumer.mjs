// ── engine-blind-to-consumer: assay writes no view for one consumer (#339) ──────
// The Intake and Maintain views, and their commands, existed for one operator's
// processes. They left the engine: a consumer builds its own view from the measurement
// with views/rows.mjs's buildRows (CONSUMERS.md, "Views a consumer builds"). A run an
// earlier engine compiled still carries their files, and it reads as before. Pinned:
//   (a) compile writes no INTAKE.md, MAINTAIN.md, views/intake.yaml or views/maintain.yaml,
//       and INDEX.md names none of them;
//   (b) `node assay.mjs intake` and `node assay.mjs maintain` are unknown commands (exit 2),
//       and help lists neither;
//   (c) a stored run carrying those files validates and compiles, compile leaves each file
//       byte for byte as it was, and Since (compile --since), compare and the ratchet read
//       it as before.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync, mkdirSync, rmSync, cpSync } from 'node:fs';
import { join } from 'node:path';
import { HERE, ROOT, negFailures, copyFixtureFindings, copyFixtureScanners } from '../harness.mjs';

export const label = 'engine-blind-to-consumer';

const OLD_FILES = ['INTAKE.md', 'MAINTAIN.md', 'views/intake.yaml', 'views/maintain.yaml'];
// what an earlier engine wrote, in its shape (views/README.md before #339), planted as is
const PLANTED = {
  'INTAKE.md': '---\ntype: doc\ntitle: "Intake — stored"\n---\n\n# Intake — stored\n\n## Open\n\n_Nothing open._\n',
  'MAINTAIN.md': '---\ntype: doc\ntitle: "Maintain — stored"\n---\n\n# Maintain — stored\n\n## Open\n\n_Nothing open._\n',
  'views/intake.yaml': '# intake.yaml — GENERATED by views/intake.mjs. Do not hand-edit.\nview: intake\nrun: stored\nyardstick: 0\ncounts:\n  requirements: 0\nopen: []\nmet: []\nto_run: []\nnot_applicable: []\nnot_seen: []\ncontradictions: []\nowner: null\n',
  'views/maintain.yaml': '# maintain.yaml — GENERATED by views/maintain.mjs. Do not hand-edit.\nview: maintain\nrun: stored\nyardstick: 0\ncounts:\n  requirements: 0\nopen: []\nmet: []\nto_run: []\nnot_applicable: []\nnot_seen: []\ncontradictions: []\n',
};

export async function run() {
  const fail = (m) => negFailures.push('engine-blind-to-consumer: ' + m);
  const assay = (...a) => spawnSync(process.execPath, [join(ROOT, 'assay.mjs'), ...a], { encoding: 'utf8' });
  const tail = (r) => String(r.stderr || r.stdout || '').trim().split('\n').slice(-3).join(' | ');
  const tmp = join(HERE, 'tmp-engine-blind'); rmSync(tmp, { recursive: true, force: true });
  mkdirSync(tmp, { recursive: true });

  // (a) a fresh compile
  const fresh = join(tmp, 'notesbox-2026-11-01');
  copyFixtureFindings('notesbox', fresh); copyFixtureScanners('notesbox', fresh);
  const c = assay('compile', fresh);
  if (c.status !== 0) fail(`compile must succeed on the notesbox fixture (exit ${c.status}): ${tail(c)}`);
  for (const f of OLD_FILES) if (existsSync(join(fresh, f))) fail(`compile writes no ${f}: the view left the engine with #339`);
  const index = existsSync(join(fresh, 'INDEX.md')) ? readFileSync(join(fresh, 'INDEX.md'), 'utf8') : '';
  if (!index) fail('compile must still write INDEX.md');
  for (const word of ['INTAKE.md', 'MAINTAIN.md', 'intake.yaml', 'maintain.yaml', 'Intake', 'Maintain']) if (index.includes(word)) fail(`INDEX.md names ${word}; it lists only the views compile writes`);
  if (!index.includes('OWNER.md')) fail('INDEX.md still lists the Owner view');

  // (b) the commands
  for (const cmd of ['intake', 'maintain']) {
    const r = assay(cmd, fresh);
    if (r.status !== 2 || !new RegExp(`unknown command "${cmd}"`).test(String(r.stderr))) fail(`node assay.mjs ${cmd} must be an unknown command, exit 2 (got exit ${r.status}: ${tail(r)})`);
  }
  const help = assay('help').stdout || '';
  for (const cmd of ['intake', 'maintain']) if (new RegExp(`^  ${cmd} {2,}`, 'm').test(help)) fail(`help must not list the ${cmd} command`);

  // (c) a stored run carrying the old files: the fresh run, with the files planted
  const stored = join(tmp, 'notesbox-2026-11-02');
  cpSync(fresh, stored, { recursive: true });
  for (const [f, text] of Object.entries(PLANTED)) { mkdirSync(join(stored, f, '..'), { recursive: true }); writeFileSync(join(stored, f), text); }
  const v = assay('validate', stored);
  if (v.status !== 0) fail(`a stored run carrying ${OLD_FILES.join(', ')} must validate (exit ${v.status}): ${tail(v)}`);
  const cs = assay('compile', stored, '--since', fresh);
  if (cs.status !== 0) fail(`a stored run carrying the old files must compile, with Since against a previous run (exit ${cs.status}): ${tail(cs)}`);
  for (const [f, text] of Object.entries(PLANTED)) {
    const now = existsSync(join(stored, f)) ? readFileSync(join(stored, f), 'utf8') : null;
    if (now !== text) fail(`compile must leave a stored run's ${f} as it was (${now === null ? 'it was removed' : 'it was rewritten'})`);
  }
  if (!existsSync(join(stored, 'SINCE.md'))) fail('Since must read a stored run carrying the old files');
  const cmp = assay('compare', join(fresh, 'yardstick.yaml'), join(stored, 'yardstick.yaml'), '--json');
  let moved = null;
  try { moved = JSON.parse(cmp.stdout); } catch { /* reported below */ }
  if (cmp.status !== 0 || !moved || !Array.isArray(moved.rows)) fail(`compare must read a stored run carrying the old files (exit ${cmp.status}): ${tail(cmp)}`);
  else if (moved.rows.some((r) => r.classification !== 'unchanged')) fail(`compare reads the stored run as before: one measurement of one map, nothing moved (got ${moved.rows.filter((r) => r.classification !== 'unchanged').map((r) => `${r.id}:${r.classification}`).join(', ')})`);
  const rt = assay('ratchet', stored);
  if (rt.status !== 0) fail(`the ratchet must read a stored run carrying the old files (exit ${rt.status}): ${tail(rt)}`);
  rmSync(tmp, { recursive: true, force: true });
}
